"""Extract Bee's geometry from public/ref/BeBetter_sheet_Bee.svg → src/filters/bee-geometry.ts

Coordinates are kept in the FRONT view's SVG units. Expression features come from the small
EXPRESSIONS cells and are rescaled into FRONT units (eye spacing 36 → 102.6).
"""
import re, json, pathlib

svg = pathlib.Path("public/ref/BeBetter_sheet_Bee.svg").read_text()
groups = [body for body in re.findall(r'<g class="character"[^>]*>(.*?)</g>', svg, re.S)]
paths = lambda g: re.findall(r'<path d="([^"]*)"', g)

front = paths(groups[0])
tail, s1, s2, s3, ear_l, _, ear_r, _, body = front[:9]

def pts(d):
    return [tuple(map(float, p)) for p in re.findall(r'([-\d.]+) ([-\d.]+)', d)]

# FRONT eye midpoint is our origin
EX, EY = round((491.6 + 594.2) / 2, 2), 791.7

# cheer pose (group 11) → FRONT units
CX, CY, CS = (1345.41 + 1382.29) / 2, 1707.61, 36.88 / 36   # eye mid + scale of that cell vs small cells
S = 102.6 / 36                                               # small → FRONT
def cheer(x, y):
    return (round((x - CX) / CS * S + EX, 2), round((y - CY) / CS * S + EY, 2))

def circle_center(d):
    p = pts(d)
    xs, ys = [a for a, _ in p], [b for _, b in p]
    return ((max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2, (max(xs) - min(xs)) / 2)

cp = paths(groups[11])
def arm(i):
    a = pts(cp[i])           # M start Q ctrl end
    paw = circle_center(cp[i + 1])
    pads = [circle_center(cp[i + k]) for k in (2, 3, 4, 5)]
    c = lambda x, y: cheer(x, y)
    r = lambda v: round(v / CS * S, 2)
    return {
        "start": c(*a[0]), "ctrl": c(*a[1]), "end": c(*a[2]),
        "paw": [*c(paw[0], paw[1]), r(paw[2])],
        "pads": [[*c(px, py), r(pr)] for px, py, pr in pads],
    }

out = f"""// Generated by scripts/extract-bee.py from public/ref/BeBetter_sheet_Bee.svg — do not edit by hand.
// Units: the sheet's FRONT view (SVG px). ORIGIN = midpoint between the eyes.

export const ORIGIN = {{ x: {EX}, y: {EY} }};
export const BODY = {json.dumps(body)};
export const EAR_L = {json.dumps(ear_l)};
export const EAR_R = {json.dumps(ear_r)};
export const TAIL: [number, number][] = {json.dumps(pts(tail))};
export const TAIL_STRIPES: [number, number][][] = {json.dumps([pts(s) for s in (s1, s2, s3)])};
export const ARM_L = {json.dumps(arm(0))} as const;
export const ARM_R = {json.dumps(arm(6))} as const;
"""
pathlib.Path("src/filters/bee-geometry.ts").write_text(out)
print("ok", len(out))
