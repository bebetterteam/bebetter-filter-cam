"""Extract a BeBetter character sheet into a TS geometry module.

  python3 scripts/extract-bebetter.py public/ref/BeBetter_sheet_Bee.svg bee
  → src/filters/bebetter/bee-geometry.ts

All sheets share one template: group 0 = FRONT view, groups 1–10 = EXPRESSIONS, group 11 = the
cheer pose (arms up). Coordinates stay in FRONT-view SVG units. Face features are measured in the
small expression cells, so we also export S = FRONT eye spacing / 36 (small-cell eye spacing).
"""
import json, pathlib, re, sys

src, name = sys.argv[1], sys.argv[2]
svg = pathlib.Path(src).read_text()
groups = re.findall(r'<g class="character"[^>]*>(.*?)</g>', svg, re.S)
elements = lambda g: re.findall(r'<path [^>]*>', g)
attr = lambda e, a: (m.group(1) if (m := re.search(rf' {a}="([^"]*)"', e)) else None)
pts = lambda d: [tuple(map(float, p)) for p in re.findall(r'([-\d.]+)[ ,]([-\d.]+)', d)]

def prim(e):
    p = {"d": attr(e, "d")}
    fill = attr(e, "fill")
    if fill and fill != "none":
        p["fill"] = fill
    if attr(e, "stroke"):
        p["stroke"] = attr(e, "stroke")
        p["width"] = float(attr(e, "stroke-width"))
        p["cap"] = attr(e, "stroke-linecap") or "butt"
    return p

front = elements(groups[0])
# the body is the one huge polygon; everything before it is behind the body
body_i = max(range(len(front)), key=lambda i: len(attr(front[i], "d")))
body = attr(front[body_i], "d")
bp = pts(body)
box = [min(x for x, _ in bp), min(y for _, y in bp), max(x for x, _ in bp), max(y for _, y in bp)]
main = attr(front[body_i], "fill")
# after the body: non-feature parts (e.g. wings) until the first white eyeball
after = front[body_i + 1:]
first_eye = next(i for i, e in enumerate(after) if attr(e, "fill") == "#FFFFFF")
back = [prim(e) for e in front[:body_i]]
front_parts = [prim(e) for e in after[:first_eye]]

# FRONT eye centers → origin + scale
def center(d):
    p = pts(d)
    return ((min(x for x, _ in p) + max(x for x, _ in p)) / 2, (min(y for _, y in p) + max(y for _, y in p)) / 2,
            (max(x for x, _ in p) - min(x for x, _ in p)) / 2)
el, er = center(attr(after[first_eye], "d")), center(attr(after[first_eye + 3], "d"))
EX, EY = round((el[0] + er[0]) / 2, 2), round(el[1], 2)
S = (er[0] - el[0]) / 36

# cheer pose: arms are the first 12 shapes (stroke + paw + 4 pads, ×2); its eyes give the cell's scale
cheer = elements(groups[11])
c_eyes = [center(attr(e, "d")) for e in cheer if attr(e, "fill") == "#FFFFFF" and len(attr(e, "d")) < 300]
shade = attr(cheer[2], "fill")
if len(c_eyes) >= 4:
    cl, cr = c_eyes[0], c_eyes[2]
    CX, CY, CS = (cl[0] + cr[0]) / 2, cl[1], (cr[0] - cl[0]) / 36
else:  # cheer cell drawn with closed eyes — fall back to Bee's template cell (identical layout)
    CX, CY, CS = 1363.85, 1707.61, 36.88 / 36
def cp(x, y):
    return [round((x - CX) / CS * S + EX, 2), round((y - CY) / CS * S + EY, 2)]

def arm(i):
    a = pts(attr(cheer[i], "d"))
    paw = center(attr(cheer[i + 1], "d"))
    pads = [center(attr(cheer[i + k], "d")) for k in (2, 3, 4, 5)]
    r = lambda v: round(v / CS * S, 2)
    return {"start": cp(*a[0]), "ctrl": cp(*a[1]), "end": cp(*a[2]), "paw": [*cp(paw[0], paw[1]), r(paw[2])],
            "pads": [[*cp(px, py), r(pr)] for px, py, pr in pads], "width": r(float(attr(cheer[i], "stroke-width")))}

geo = {
    "ORIGIN": {"x": EX, "y": EY}, "S": round(S, 4), "MAIN": main, "SHADE": shade,
    "BODY": body, "BODY_BOX": box, "BACK": back, "FRONT": front_parts, "ARM_L": arm(0), "ARM_R": arm(6),
}
out = pathlib.Path(f"src/filters/bebetter/{name}-geometry.ts")
out.write_text(
    f"// Generated by scripts/extract-bebetter.py from {src} — do not edit by hand.\n"
    "// Units: the sheet's FRONT view (SVG px). ORIGIN = midpoint between the eyes.\n"
    'import type { Geometry } from "./rig";\n\n'
    f"export const geometry: Geometry = {json.dumps(geo, indent=1)};\n"
)
print(out, "back", len(back), "front", len(front_parts), "S", round(S, 4), "origin", EX, EY, "box", box)
